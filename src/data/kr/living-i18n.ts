/** Localized seasonal state, falling back to the Vietnamese source. */
export function krSeasonalState(month: number, destinationId: string, source: string, locale: string): string {
  if (locale === "vi") return source;
  return SEASONAL[locale as ContentLocale]?.[`${month}:${destinationId}`] ?? source;
}

export function krFestivalName(id: string, source: string, locale: string): string {
  if (locale === "vi") return source;
  return FESTIVAL[locale as ContentLocale]?.[id]?.name ?? source;
}

export function krFestivalDescription(id: string, source: string, locale: string): string {
  if (locale === "vi") return source;
  return FESTIVAL[locale as ContentLocale]?.[id]?.description ?? source;
}
